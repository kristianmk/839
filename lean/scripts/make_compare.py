"""Write scripts/Compare<X>.lean from Challenge<X>.lean: the text of the Challenge file is placed
in a namespace `Chal`, on top of the corresponding Solution file, and each `sorry` is replaced by
the Solution theorem of the same name. If the result compiles, the Solution file proves exactly
the statements of the Challenge file, with the definitions as written there.

usage (from the project directory): python3 scripts/make_compare.py
then: lake env lean scripts/Compare839.lean  (and Compare673.lean, CompareCeilings.lean, CompareFurther.lean,
Compare889.lean)
"""
import re
for tag, sol in (('839', 'Solution839'), ('673', 'Solution673'), ('Ceilings', 'SolutionCeilings'), ('Further', 'SolutionFurther'),
                 ('889', 'Solution889')):
    src = open(f'Challenge{tag}.lean').read()
    i = src.index('import Mathlib'); body = src[i + len('import Mathlib'):]
    names = re.findall(r'^theorem (\w+)', body, flags=re.M)
    parts = re.split(r'(^theorem \w+)', body, flags=re.M)
    out = [parts[0]]
    for k in range(1, len(parts), 2):
        name = parts[k].split()[1]; txt = parts[k + 1]
        assert txt.count('  sorry') == 1, (tag, name)
        out.append(parts[k] + txt.replace('  sorry', f'  exact _root_.{name}'))
    text = (f'/-\nscripts/Compare{tag}.lean — GENERATED by scripts/make_compare.py from Challenge{tag}.lean.\n'
            f'The statements of Challenge{tag}.lean, in the namespace `Chal`, proved by the theorems of {sol}.lean.\n-/\n'
            f'import {sol}\nnamespace Chal\n' + ''.join(out).rstrip('\n') + '\n\nend Chal\n\n'
            + ''.join(f'#print axioms Chal.{n}\n' for n in names))
    open(f'scripts/Compare{tag}.lean', 'w').write(text)
    print(f'scripts/Compare{tag}.lean:', len(names), 'theorems')
